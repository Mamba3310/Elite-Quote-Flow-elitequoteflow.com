import { readFile, writeFile } from 'node:fs/promises';
const path='public/index.html';
let html=await readFile(path,'utf8');
const pricingStart=html.indexOf('<section class="landing-pricing"');
const pricingEnd=pricingStart<0?-1:html.indexOf('</section>',pricingStart)+('</section>'.length);
if(pricingStart<0||pricingEnd<('</section>'.length))throw Error('Cannot locate existing pricing section.');
const pricing=html.slice(pricingStart,pricingEnd);
const gridStart=pricing.indexOf('<div class="landing-pricing-grid">');
const noteStart=pricing.indexOf('<p class="landing-pricing-note">');
if(gridStart<0||noteStart<0)throw Error('Pricing cards or note missing.');
const gridClose=noteStart-1;
if(gridClose<=gridStart)throw Error('Pricing grid ending missing.');
const pricingCards=pricing.slice(gridStart,gridClose);
const noteEnd=pricing.indexOf('</p>',noteStart)+('</p>'.length);
const pricingNote=pricing.slice(noteStart,noteEnd);
const offerStart=html.indexOf('<section class="landing-offer"');
const featuresStart=offerStart<0?-1:html.indexOf('<div class="landing-features">',offerStart);
if(featuresStart<0)throw Error('Cannot locate landing offer section.');
html=html.slice(0,featuresStart)+pricingCards+pricingNote+html.slice(featuresStart);
const adjustedPricingStart=html.indexOf('<section class="landing-pricing"');
const adjustedPricingEnd=adjustedPricingStart<0?-1:html.indexOf('</section>',adjustedPricingStart)+('</section>'.length);
if(adjustedPricingEnd<('</section>'.length))throw Error('Pricing section missing after inserting cards.');
html=html.slice(0,adjustedPricingStart)+html.slice(adjustedPricingEnd);
await writeFile(path,html,'utf8');
console.log('Moved Free and Pro pricing cards directly under the transparent-start copy and removed the duplicate pricing block.');
